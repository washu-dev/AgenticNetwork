"""Autonomous LLM agent loop for the coding agent.

The coding agent is itself an agent — an LLM that reasons over the user's
natural-language prompt and decides which tools to invoke. The three tools
exposed to the LLM are:

- ``run_coder(task, files=None)`` — delegate a coding task to ``mini-swe-agent``
  inside a sandboxed scratch workspace shared across calls within one request.
- ``discover_agents(skill_query)`` — search the AGNTCY Directory for agents
  advertising a particular skill.
- ``send_email_via_directory(to, subject, body, files=None)`` — discover an
  email-capable agent in the directory and ask it to send the listed files
  (inlined into the email body, since the email agent has no attachment slot).

The loop is async: tool handlers can be async, and the LLM call uses
``litellm.acompletion``. Tests inject a stub ``completion_fn`` to drive
deterministic conversations without an LLM provider.
"""
from __future__ import annotations

import asyncio
import json
import logging
import time
from dataclasses import dataclass, field
from typing import Any, Awaitable, Callable, Mapping

logger = logging.getLogger("coding_agent.agent_loop")

ToolHandler = Callable[[Mapping[str, Any]], Awaitable[dict[str, Any]]]


SYSTEM_PROMPT = """You are an autonomous coding assistant operating over an A2A agent network.

You have three tools:

- run_coder(task, files=None): delegates real coding work to mini-swe-agent — \
a sandboxed shell-loop runner that writes/modifies source files in a scratch \
workspace. The workspace persists across run_coder calls within one request, \
so successive calls can build on prior work. The result includes \
generated_files (path, content, action), a submission summary, and stats \
(n_calls, cost, exit_status).

- discover_agents(skill_query): searches the AGNTCY Directory for agents \
advertising a skill (e.g. 'email/send'). Use this to see what's available \
before invoking another agent.

- send_email_via_directory(to, subject, body, files=None, confirmed=False): \
finds an email-capable agent in the directory and asks it to send the listed \
files (path + content) to `to`. Files are inlined into the email body as \
plaintext code blocks — the email agent has no attachment slot today. The \
email agent requires user confirmation before actually sending. Call this \
first WITHOUT `confirmed=true`; the caller (the user) will be prompted, the \
conversation will pause, and their reply will come back to you as the tool \
result. If they approve, call this tool again with the SAME args plus \
`confirmed=true` to actually send. If they decline, do NOT retry — finish \
with a short final message acknowledging that the files were generated but \
not emailed.

Workflow:
1. State your plan in one short sentence.
2. Use run_coder to do the actual code work. Pass any user-supplied files as \
the seed.
3. If the user asked for delivery (e.g. \"email this to alice\"), pick the \
relevant files from run_coder's generated_files and call \
send_email_via_directory (the first call WITHOUT `confirmed=true`).
4. After the user's confirmation reply comes back, decide whether to retry \
with `confirmed=true` or to abort delivery.
5. When done, reply with a concise summary of what you did. Do not call any \
more tools after that.

Constraints:
- Never run shell commands directly — only via run_coder.
- The user's natural-language prompt is your only spec. There is no separate \
skill or routing metadata.
- Keep tool calls focused; two run_coder calls per request is usually enough.
- Files generated by run_coder are saved to the user's response regardless of \
whether email delivery happens, so a "no" answer to confirmation is safe — \
the user still gets the files.
"""


