class PendingUserConfirmation(Exception):
    """Raised by a tool handler to pause the agent loop pending user input.

    The handler attaches a human-readable ``prompt`` (shown to the user as
    the A2A ``input-required`` message) and an optional ``payload`` carrying
    any data the executor wants to persist alongside the pause (e.g. the
    discovered agent's id, the original tool args).
    """

    def __init__(self, prompt: str, *, payload: dict[str, Any] | None = None) -> None:
        super().__init__(prompt)
        self.prompt = prompt
        self.payload = payload or {}


@dataclass
class ToolInvocation:
    name: str
    args: dict[str, Any]
    result: dict[str, Any] | None = None
    error: str | None = None


@dataclass
class AgentTrace:
    final_message: str = ""
    exit_reason: str = "completed"  # completed | input_required | step_limit | time_limit | error
    n_steps: int = 0
    elapsed: float = 0.0
    messages: list[dict[str, Any]] = field(default_factory=list)
    tool_calls: list[ToolInvocation] = field(default_factory=list)
    pending: dict[str, Any] | None = None


def _coerce_args(arguments: Any) -> dict[str, Any]:
    if isinstance(arguments, Mapping):
        return dict(arguments)
    if isinstance(arguments, str):
        try:
            parsed = json.loads(arguments)
        except json.JSONDecodeError:
            return {"_raw": arguments}
        if isinstance(parsed, Mapping):
            return dict(parsed)
        return {"_value": parsed}
    return {}


def _serialize_tool_calls(tool_calls: Any) -> list[dict[str, Any]]:
    """Normalize litellm/openai tool_call objects into JSON-able dicts."""
    out: list[dict[str, Any]] = []
    for tc in tool_calls or []:
        if isinstance(tc, Mapping):
            fn = tc.get("function") or {}
            out.append({
                "id": tc.get("id"),
                "type": tc.get("type", "function"),
                "function": {
                    "name": fn.get("name") if isinstance(fn, Mapping) else getattr(fn, "name", None),
                    "arguments": fn.get("arguments") if isinstance(fn, Mapping) else getattr(fn, "arguments", ""),
                },
            })
        else:
            fn = getattr(tc, "function", None)
            out.append({
                "id": getattr(tc, "id", None),
                "type": getattr(tc, "type", "function"),
                "function": {
                    "name": getattr(fn, "name", None) if fn else None,
                    "arguments": getattr(fn, "arguments", "") if fn else "",
                },
            })
    return out


async def _emit(progress_callback: ProgressCallback | None, event: dict[str, Any]) -> None:
    """Best-effort progress emission — never let a callback crash the loop."""
    if progress_callback is None:
        return
    try:
        await progress_callback(event)
    except Exception:
        logger.exception("progress_callback raised on event=%s", event.get("kind"))


async def _completion_with_heartbeat(
    completion_fn: Callable[..., Awaitable[Any]],
    *,
    model: str,
    messages: list[dict[str, Any]],
    progress_callback: ProgressCallback | None,
    heartbeat_interval_s: float,
    step: int,
) -> Any:
    """Run the LLM call and emit a 'still_processing' event every ``heartbeat_interval_s``.

    The PI agent's HTTP client has a 30s read timeout. As long as bytes
    flow over the SSE channel within that window, the timeout never trips.
    The heartbeat doesn't speed up the LLM — it just keeps the connection
    alive and tells the user we're still thinking.
    """
    llm_task = asyncio.ensure_future(
        completion_fn(
            model=model,
            messages=messages,
            tools=TOOL_SCHEMAS,
            tool_choice="auto",
        )
    )
    started = time.monotonic()
    while True:
        try:
            return await asyncio.wait_for(asyncio.shield(llm_task), timeout=heartbeat_interval_s)
        except asyncio.TimeoutError:
            elapsed = time.monotonic() - started
            await _emit(progress_callback, {
                "kind": "still_processing",
                "step": step,
                "elapsed_s": round(elapsed, 1),
            })


async def run_agent_loop(
    user_prompt: str,
    *,
    model: str,
    tool_handlers: dict[str, ToolHandler],
    completion_fn: Callable[..., Awaitable[Any]] | None = None,
    system_prompt: str = SYSTEM_PROMPT,
    step_limit: int = 8,
    time_limit_s: float = 900.0,
    initial_messages: list[dict[str, Any]] | None = None,
    initial_tool_invocations: list[ToolInvocation] | None = None,
    initial_n_steps: int = 0,
    progress_callback: ProgressCallback | None = None,
    heartbeat_interval_s: float = 25.0,
) -> AgentTrace:
    """Drive the LLM agent loop until it stops calling tools or hits a limit.

    ``completion_fn`` defaults to ``litellm.acompletion`` and is overridable
    for tests. It must return an object with the OpenAI-compatible shape
    ``response.choices[0].message`` exposing ``content`` and (optional)
    ``tool_calls``.

    Resume: pass ``initial_messages`` (the persisted message history with
    any newly-injected tool result for the previously-pending tool call)
    and the prior ``initial_tool_invocations`` / ``initial_n_steps``. When
    a tool handler raises ``PendingUserConfirmation``, the loop appends the
    pause prompt as the tool's response and exits with
    ``exit_reason="input_required"`` and ``trace.pending`` populated.
    """
    if completion_fn is None:
        import litellm  # imported lazily so tests don't need it
        completion_fn = litellm.acompletion

    if initial_messages is not None:
        messages: list[dict[str, Any]] = list(initial_messages)
    else:
        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ]
    trace = AgentTrace(messages=messages)
    if initial_tool_invocations:
        trace.tool_calls.extend(initial_tool_invocations)
    trace.n_steps = initial_n_steps
    started = time.monotonic()

    while True:
        if trace.n_steps >= step_limit:
            trace.exit_reason = "step_limit"
            trace.final_message = trace.final_message or "(step limit reached)"
            break
        if (time.monotonic() - started) >= time_limit_s:
            trace.exit_reason = "time_limit"
            trace.final_message = trace.final_message or "(time limit reached)"
            break

        trace.n_steps += 1
        logger.info(
            "agent_loop step=%d messages=%d tools_used=%d",
            trace.n_steps, len(messages), len(trace.tool_calls),
        )
        await _emit(progress_callback, {
            "kind": "round_started",
            "step": trace.n_steps,
        })
        response = await _completion_with_heartbeat(
            completion_fn,
            model=model,
            messages=messages,
            progress_callback=progress_callback,
            heartbeat_interval_s=heartbeat_interval_s,
            step=trace.n_steps,
        )

        choice = response.choices[0]
        msg = choice.message
        content = getattr(msg, "content", None)
        if isinstance(msg, Mapping):
            content = msg.get("content", content)
            raw_tool_calls = msg.get("tool_calls")
        else:
            raw_tool_calls = getattr(msg, "tool_calls", None)
        tool_calls = _serialize_tool_calls(raw_tool_calls)

        assistant_message: dict[str, Any] = {"role": "assistant", "content": content or ""}
        if tool_calls:
            assistant_message["tool_calls"] = tool_calls
        messages.append(assistant_message)

        if not tool_calls:
            trace.final_message = (content or "").strip()
            trace.exit_reason = "completed"
            await _emit(progress_callback, {
                "kind": "thought",
                "step": trace.n_steps,
                "content": trace.final_message,
                "is_final": True,
            })
            break

        if content:
            await _emit(progress_callback, {
                "kind": "thought",
                "step": trace.n_steps,
                "content": str(content).strip(),
                "is_final": False,
            })

        paused = False
        for call_index, call in enumerate(tool_calls):
            tool_name = (call.get("function") or {}).get("name") or ""
            args = _coerce_args((call.get("function") or {}).get("arguments"))
            invocation = ToolInvocation(name=tool_name, args=args)
            trace.tool_calls.append(invocation)
            logger.info(
                "agent_loop tool_call name=%s args_keys=%s",
                tool_name, sorted(args.keys()),
            )
            await _emit(progress_callback, {
                "kind": "tool_call",
                "step": trace.n_steps,
                "name": tool_name,
                "args_keys": sorted(args.keys()),
            })

            handler = tool_handlers.get(tool_name)
            if handler is None:
                invocation.error = f"unknown tool {tool_name!r}"
                tool_result: dict[str, Any] = {"error": invocation.error}
            else:
                try:
                    raw_result = await handler(args)
                    if asyncio.iscoroutine(raw_result):
                        raw_result = await raw_result
                    tool_result = (
                        raw_result if isinstance(raw_result, dict) else {"value": raw_result}
                    )
                    invocation.result = tool_result
                except PendingUserConfirmation as pause:
                    invocation.result = {
                        "status": "pending_user_confirmation",
                        "prompt": pause.prompt,
                    }
                    trace.pending = {
                        "tool_call_id": call.get("id"),
                        "tool_name": tool_name,
                        "args": args,
                        "prompt": pause.prompt,
                        "payload": pause.payload,
                    }
                    trace.exit_reason = "input_required"
                    trace.final_message = pause.prompt
                    messages.append({
                        "role": "tool",
                        "tool_call_id": call.get("id"),
                        "name": tool_name,
                        "content": json.dumps(invocation.result, default=str),
                    })
                    for skipped in tool_calls[call_index + 1 :]:
                        messages.append({
                            "role": "tool",
                            "tool_call_id": skipped.get("id"),
                            "name": (skipped.get("function") or {}).get("name") or "",
                            "content": json.dumps({
                                "skipped": "deferred until user confirmation"
                            }),
                        })
                    paused = True
                    logger.info(
                        "agent_loop paused: tool=%s prompt=%r",
                        tool_name, pause.prompt[:120],
                    )
                    break
                except Exception as exc:
                    invocation.error = f"{type(exc).__name__}: {exc}"
                    tool_result = {"error": invocation.error}
                    logger.exception("tool %s raised", tool_name)

            messages.append({
                "role": "tool",
                "tool_call_id": call.get("id"),
                "name": tool_name,
                "content": json.dumps(tool_result, default=str),
            })
            await _emit(progress_callback, {
                "kind": "tool_result",
                "step": trace.n_steps,
                "name": tool_name,
                "result_keys": sorted((invocation.result or {}).keys()) if invocation.result else [],
                "error": invocation.error,
            })

        if paused:
            break

    trace.elapsed = time.monotonic() - started
    logger.info(
        "agent_loop done exit=%s steps=%d tools=%d elapsed=%.2fs",
        trace.exit_reason, trace.n_steps, len(trace.tool_calls), trace.elapsed,
    )
    return trace


def serialize_invocations(invocations: list[ToolInvocation]) -> list[dict[str, Any]]:
    return [
        {"name": inv.name, "args": inv.args, "result": inv.result, "error": inv.error}
        for inv in invocations
    ]


def deserialize_invocations(data: list[dict[str, Any]]) -> list[ToolInvocation]:
    return [
        ToolInvocation(
            name=str(d.get("name") or ""),
            args=dict(d.get("args") or {}),
            result=d.get("result") if isinstance(d.get("result"), dict) else None,
            error=d.get("error"),
        )
        for d in (data or [])
    ]
